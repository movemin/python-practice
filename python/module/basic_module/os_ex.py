# 운영체제와 관련된 정보도 추출할 수 있지만,
# 운영체제가 제공하는 파일 처리와 관련된 기능을 활용할 때 활용 가능
import os

# ex
print(os.listdir("."))  # : 특정한 디렉토리 내부에 있는 요소들을 확인할 수 있다.
os.mkdir("hello")       # : 특정한 폴더를 만들 수 있다.
os.rmdir("hello")       # : 특정한 폴더를 제거
os.rename("ㅇㅇ", "ㅁㅁ") # : 특정한 이름의 파일을 특정한 이름으로 변경 가능
os.remove("ㅇㅇ")        # : 특정한 데이터를 제거할 수 있다.
os.system("시스템 명령어") # : 시스템 명령어 실행 가능